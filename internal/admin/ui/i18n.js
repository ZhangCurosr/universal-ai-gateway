function detect() {
  try {
    const saved = sessionStorage.getItem(LANG_KEY);
    if (saved === 'zh' || saved === 'en') return saved;
  } catch (_) { /* 存储不可用时按浏览器语言 */ }
  const nav = (navigator.language || '').toLowerCase();
  return nav.startsWith('zh') ? 'zh' : 'en';
}

let lang = detect();

export function getLang() { return lang; }

export function setLang(next) {
  lang = next === 'zh' ? 'zh' : 'en';
  try { sessionStorage.setItem(LANG_KEY, lang); } catch (_) { /* 只影响下次打开 */ }
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
}

export function t(key, vars) {
  const s = MESSAGES[lang][key] ?? MESSAGES.en[key] ?? key;
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

export function fmtInt(n) {
  if (typeof n !== 'number' || !Number.isFinite(n)) return t('common.dash');
  return new Intl.NumberFormat(lang === 'zh' ? 'zh-CN' : 'en-US').format(n);
}

// fmtTime 返回本地时区的时间文本；调用方把原始 UTC 值放进 title（UI-14）。
export function fmtTime(iso) {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return String(iso || '');
  return d.toLocaleString(lang === 'zh' ? 'zh-CN' : 'en-US', { hour12: false });
}

export function fmtDuration(seconds) {
  const s = Math.max(0, Math.floor(seconds || 0));
  const d = Math.floor(s / 86400), h = Math.floor((s % 86400) / 3600), m = Math.floor((s % 3600) / 60);
  if (d > 0) return t('time.days', { d, h });
  if (h > 0) return t('time.hours', { h, m });
  return t('time.minutes', { m });
}

